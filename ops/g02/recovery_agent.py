#!/usr/bin/env python3
"""Staging-only G02 host probe and Firestore evidence writer.

Uses Application Default Credentials (ADC); never reads or emits service-account
JSON. Requires explicit FIREBASE_ENV=staging and a dedicated staging project.
This is a diagnostic probe, not a service restarter or production control agent.
"""
from __future__ import annotations

import json
import os
import platform
import shutil
import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

RUNNER_NAME = os.getenv("RUNNER_NAME", "")
RUNNER_LABEL = "lingo-legacy-g02-staging"


def command(argv: list[str], timeout: int = 8) -> dict[str, Any]:
    try:
        result = subprocess.run(argv, capture_output=True, text=True, timeout=timeout, check=False)
        return {
            "exit_code": result.returncode,
            "stdout": result.stdout[-3000:].strip(),
            "stderr": result.stderr[-1000:].strip(),
        }
    except (OSError, subprocess.TimeoutExpired) as exc:
        return {"error_type": type(exc).__name__, "error": str(exc)[:300]}


def main() -> int:
    if os.getenv("FIREBASE_ENV") != "staging":
        print("REFUSED: FIREBASE_ENV must equal 'staging'.", file=sys.stderr)
        return 2
    project_id = os.getenv("FIREBASE_PROJECT_ID", "").strip()
    if not project_id or project_id == "lingo-legacy-production":
        print("REFUSED: configure a dedicated non-production FIREBASE_PROJECT_ID.", file=sys.stderr)
        return 2
    if "staging" not in RUNNER_NAME.lower():
        print("REFUSED: RUNNER_NAME must explicitly identify the staging runner.", file=sys.stderr)
        return 2
    if platform.system() != "Linux":
        print("REFUSED: this staging probe requires Linux.", file=sys.stderr)
        return 2

    evidence: dict[str, Any] = {
        "schema": "lingo-g02-staging-host-evidence-v1",
        "environment": "staging",
        "firebase_project_id": project_id,
        "runner_name": RUNNER_NAME,
        "runner_label": RUNNER_LABEL,
        "captured_utc": datetime.now(timezone.utc).isoformat(),
        "github": {
            "run_id": os.getenv("GITHUB_RUN_ID", ""),
            "run_attempt": os.getenv("GITHUB_RUN_ATTEMPT", ""),
            "sha": os.getenv("GITHUB_SHA", ""),
            "repository": os.getenv("GITHUB_REPOSITORY", ""),
            "workflow": os.getenv("GITHUB_WORKFLOW", ""),
            "job": os.getenv("GITHUB_JOB", ""),
        },
        "host": {
            "platform": platform.platform(),
            "python": sys.version.split()[0],
            "uptime": command(["uptime"]),
            "root_disk": command(["df", "-h", "/"]),
            "runner_listener_processes": command(
                ["bash", "-lc", "pgrep -af 'Runner.Listener|Runner.Worker' || true"]
            ),
            "tools": {
                name: shutil.which(name) is not None
                for name in ("bash", "python3", "curl", "systemctl", "sha256sum")
            },
        },
    }

    # Write a local evidence file before the remote write so the workflow can
    # upload it even if Firestore access is denied.
    out = Path(os.getenv("G02_EVIDENCE_DIR", "g02-staging-evidence"))
    out.mkdir(mode=0o700, parents=True, exist_ok=True)
    local_path = out / "staging-host-evidence.json"
    local_path.write_text(json.dumps(evidence, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    local_path.chmod(0o600)

    try:
        import firebase_admin
        from firebase_admin import firestore
        # Uses ADC / workload identity. No credential file path or secret material.
        if not firebase_admin._apps:
            firebase_admin.initialize_app(options={"projectId": project_id})
        db = firestore.client()
        # One immutable record per run/attempt; avoid overwriting previous evidence.
        run_id = evidence["github"]["run_id"]
        attempt = evidence["github"]["run_attempt"]
        if not run_id or not attempt:
            raise RuntimeError("GITHUB_RUN_ID and GITHUB_RUN_ATTEMPT are required")
        doc_id = f"{run_id}-{attempt}"
        db.collection("g02_staging_evidence").document(doc_id).create(evidence)
        evidence["firestore"] = {"status": "written", "collection": "g02_staging_evidence", "document_id": doc_id}
        print(json.dumps(evidence["firestore"], sort_keys=True))
        # Update local record with write result, then hash is generated by workflow.
        local_path.write_text(json.dumps(evidence, indent=2, sort_keys=True) + "\n", encoding="utf-8")
        local_path.chmod(0o600)
        return 0
    except Exception as exc:
        # Avoid logging exception text, which can contain project/network details.
        evidence["firestore"] = {"status": "failed", "error_type": type(exc).__name__}
        local_path.write_text(json.dumps(evidence, indent=2, sort_keys=True) + "\n", encoding="utf-8")
        local_path.chmod(0o600)
        print(f"Firestore evidence write failed: {type(exc).__name__}", file=sys.stderr)
        return 3


if __name__ == "__main__":
    raise SystemExit(main())
